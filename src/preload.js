'use strict';
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('pet', {
  init: () => ipcRenderer.invoke('pet:init'),
  say: (text) => ipcRenderer.invoke('pet:say', { text }),
  config: (patch) => ipcRenderer.invoke('pet:config', patch),
  probe: () => ipcRenderer.invoke('pet:probe'),
  avatars: () => ipcRenderer.invoke('pet:avatars'),
  scale: (k) => ipcRenderer.invoke('pet:scale', { scale: k }),
  resize: (w, h) => ipcRenderer.invoke('pet:resize', { w, h }),
  hit: (v) => ipcRenderer.send('pet:hit', v),
  audioDone: () => ipcRenderer.send('pet:audio-done'),
  audioStarted: () => ipcRenderer.send('pet:audio-started'),
  record: () => ipcRenderer.send('pet:record'),
  listen: (v) => ipcRenderer.send('pet:listen', v),
  asrStatus: (opts) => ipcRenderer.invoke('pet:asr-status', opts || {}),
  openPrivacy: (kind) => ipcRenderer.send('pet:open-privacy', kind),
  drag: (a) => ipcRenderer.send('pet:drag', a),
  vis: (v) => ipcRenderer.send('pet:vis', v),
  quit: () => ipcRenderer.send('pet:quit'),
  stopSpeak: () => ipcRenderer.send('pet:stop-speak'),
  log: (m) => ipcRenderer.send('pet:log', m),
  open: (what) => ipcRenderer.send('pet:open', what),
  openWebSource: url => ipcRenderer.invoke('pet:open-web-source', url),
  // 独立窗口（设置 / 动作列表）用：拿初始数据、把动作转给角色窗口演
  panelInit: () => ipcRenderer.invoke('pet:panel-init'),
  panelMotion: (key) => ipcRenderer.send('pet:panel-motion', key),
  // 大脑 / 嘴巴
  brainInfo: () => ipcRenderer.invoke('pet:brain-info'),
  workbuddyOpen: () => ipcRenderer.invoke('pet:workbuddy-open'),
  brainModels: (brain) => ipcRenderer.invoke('pet:brain-models', brain),
  brainTest: (brain) => ipcRenderer.invoke('pet:brain-test', brain),
  ttsInfo: () => ipcRenderer.invoke('pet:tts-info'),
  chpDiscover: (patch) => ipcRenderer.invoke('pet:chp-discover', patch),
  chpHelp: () => ipcRenderer.send('pet:chp-help'),
  ttsDownload: () => ipcRenderer.invoke('pet:tts-download'),
  ttsCheck: () => ipcRenderer.invoke('pet:tts-check'),
  ttsDlState: () => ipcRenderer.invoke('pet:tts-dl-state'),
  ttsCancel: () => ipcRenderer.send('pet:tts-cancel'),
  ttsDelete: () => ipcRenderer.invoke('pet:tts-delete'),
  ttsTest: () => ipcRenderer.invoke('pet:tts-test'),
  interact: (region) => ipcRenderer.invoke('pet:interact', region),
  memoryStats: () => ipcRenderer.invoke('pet:memory-stats'),
  memoryMaintain: mode => ipcRenderer.invoke('pet:memory-maintain', mode),
  memoryMaintenanceStatus: () => ipcRenderer.invoke('pet:memory-maintenance-status'),
  memoryUnlock: () => ipcRenderer.invoke('pet:memory-unlock'),
  memoryList: (options) => ipcRenderer.invoke('pet:memory-list', options),
  memorySources: (ids) => ipcRenderer.invoke('pet:memory-sources', ids),
  memoryUpdate: (id, content) => ipcRenderer.invoke('pet:memory-update', { id, content }),
  memoryResolveConflict: (id) => ipcRenderer.invoke('pet:memory-resolve-conflict', id),
  memoryResolveDoubt: (id, options) => ipcRenderer.invoke('pet:memory-resolve-doubt', { id, ...(options || {}) }),
  memoryRemove: (id) => ipcRenderer.invoke('pet:memory-remove', id),
  memoryClear: () => ipcRenderer.invoke('pet:memory-clear'),
  memoryExport: (passphrase) => ipcRenderer.invoke('pet:memory-export', passphrase),
  memoryRestore: (passphrase) => ipcRenderer.invoke('pet:memory-restore', passphrase),
  taskStatus: () => ipcRenderer.invoke('pet:task-status'),
  desktopRefresh: () => ipcRenderer.invoke('pet:task-status'),
  taskStart: (options) => ipcRenderer.invoke('pet:task-start', options),
  taskStop: () => ipcRenderer.invoke('pet:task-stop'),
  taskAccept: () => ipcRenderer.invoke('pet:task-accept'),
  desktopPermission: () => ipcRenderer.invoke('pet:desktop-permission'),
  desktopInsert: (text) => ipcRenderer.invoke('pet:desktop-insert', text),
  watchList: () => ipcRenderer.invoke('watch:list'),
  watchPause: (id) => ipcRenderer.invoke('watch:pause', id),
  watchResume: (id) => ipcRenderer.invoke('watch:resume', id),
  watchStop: (id) => ipcRenderer.invoke('watch:stop', id),
  watchCheck: (id) => ipcRenderer.invoke('watch:check', id),
  on: (cb) => {
    ipcRenderer.on('pet:ev', (_e, d) => cb(d));
  },
});
